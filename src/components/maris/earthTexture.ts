// Point-in-polygon test for filling continents
function pointInPolygon(x: number, y: number, polygon: [number, number][]): boolean {
  let inside = false;
  for (let i = 0, j = polygon.length - 1; i < polygon.length; j = i++) {
    const xi = polygon[i][1], yi = polygon[i][0];
    const xj = polygon[j][1], yj = polygon[j][0];
    const intersect = ((yi > y) !== (yj > y)) && (x < (xj - xi) * (y - yi) / (yj - yi) + xi);
    if (intersect) inside = !inside;
  }
  return inside;
}

export function generateEarthTexture(width: number, height: number): HTMLCanvasElement {
  const canvas = document.createElement("canvas");
  canvas.width = width;
  canvas.height = height;
  const ctx = canvas.getContext("2d")!;

  // Ocean base — deep blue
  ctx.fillStyle = "#0a1e38";
  ctx.fillRect(0, 0, width, height);

  // Add subtle ocean texture noise
  const imageData = ctx.getImageData(0, 0, width, height);
  const data = imageData.data;
  for (let y = 0; y < height; y++) {
    for (let x = 0; x < width; x++) {
      const idx = (y * width + x) * 4;
      const noise = (Math.random() - 0.5) * 6;
      data[idx] = Math.max(0, Math.min(255, data[idx] + noise));
      data[idx + 1] = Math.max(0, Math.min(255, data[idx + 1] + noise));
      data[idx + 2] = Math.max(0, Math.min(255, data[idx + 2] + noise + 3));
    }
  }
  ctx.putImageData(imageData, 0, 0);

  // Draw continents
  ctx.fillStyle = "#1a3040";
  ctx.strokeStyle = "#2a6688";
  ctx.lineWidth = 1;

  CONTINENTS.forEach((continent) => {
    ctx.beginPath();
    continent.forEach(([lat, lon], i) => {
      const x = ((lon + 180) / 360) * width;
      const y = ((90 - lat) / 180) * height;
      if (i === 0) ctx.moveTo(x, y);
      else ctx.lineTo(x, y);
    });
    ctx.closePath();
    ctx.fill();
    ctx.stroke();
  });

  // Add subtle land texture
  const landImageData = ctx.getImageData(0, 0, width, height);
  const ld = landImageData.data;
  for (let y = 0; y < height; y++) {
    for (let x = 0; x < width; x++) {
      const idx = (y * width + x) * 4;
      // If pixel is land-colored (greenish-blue range)
      if (ld[idx] > 20 && ld[idx] < 35 && ld[idx + 1] > 40 && ld[idx + 1] < 60) {
        const noise = (Math.random() - 0.5) * 8;
        ld[idx] = Math.max(0, Math.min(255, ld[idx] + noise));
        ld[idx + 1] = Math.max(0, Math.min(255, ld[idx + 1] + noise));
        ld[idx + 2] = Math.max(0, Math.min(255, ld[idx + 2] + noise));
      }
    }
  }
  ctx.putImageData(landImageData, 0, 0);

  return canvas;
}

